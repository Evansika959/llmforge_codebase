"""Regenerate the prospective-selection pool, with every free config statistic recorded.

This script did not exist when runs/supernet/gt135_prosp was built -- the pool was generated by an inline
heredoc, so the 16 trained architectures had no reproducible provenance and POOL.json stored only
w/sh/kv/slice/slice_resid. Review flagged three consequences, all real:

  1. The pool-level correlation between slice_resid and `het` could not be checked. In the 16
     selected it is +0.814, and `het` is a FREE statistic -- mean coefficient of variation of the
     four per-layer knob vectors, no supernet and no forward pass. So the experiment as built
     cannot separate "the supernet knows something" from "the slice is a heterogeneity meter".
  2. The fair top-1 comparison was impossible. The slice chose the 16-architecture candidate set,
     then "won" top-1 within it; free baselines never got to pick from the same 260.
  3. The reported partial r could not be reproduced from the artefacts.

Rerunning with the same seed reproduces the same 260 configs and therefore the same 16, so the
already-trained ground truth stays valid -- this adds columns, it does not move the design.
"""
import argparse, json, os, random
import numpy as np
from llmforge.supernet.paths import RUNS
from llmforge.paths import HELDOUT

KNOBS = ("d_qk", "d_v", "n_h", "d_mlp")


def build_pool(spec, n_pool=260, per=4, seed=8080, tw=0.555, ts=0.22,
               w_tol=0.006, s_tol=0.012):
    from llmforge.supernet.space import ElasticConfig
    from llmforge.supernet.elastic.sampler import head_grid
    W0 = ElasticConfig.full(spec).weight_params(include_embed=False)
    groups = [(i, min(i + per, spec.n_layers)) for i in range(0, spec.n_layers, per)]
    rng = random.Random(seed)
    grids = {"d_qk": spec.qk_grid, "d_v": spec.qk_grid,
             "n_h": head_grid(spec), "d_mlp": spec.mlp_grid}
    pool = []
    while len(pool) < n_pool:
        per_layer = {}
        for k, g in grids.items():
            v = [rng.choice(g) for _ in range(len(groups))]
            per_layer[k] = [v[i] for i, (a, b) in enumerate(groups) for _ in range(b - a)]
        c = ElasticConfig(spec, per_layer["d_qk"], per_layer["d_v"],
                          [spec.n_kv] * spec.n_layers, per_layer["n_h"], per_layer["d_mlp"])
        w = c.weight_params(include_embed=False) / W0
        if abs(w - tw) >= w_tol:
            continue
        sh = c.attn_params() / (c.attn_params() + c.mlp_params())
        if abs(sh - ts) >= s_tol:
            continue
        row = {"per": per_layer, "w": w, "sh": sh, "kv": c.kv_frac()}
        # Free statistics: computable from the config alone, no supernet, no forward pass.
        for k in KNOBS:
            row[f"mean_{k}"] = float(np.mean(per_layer[k]))
            row[f"sd_{k}"] = float(np.std(per_layer[k]))
        row["het"] = float(np.mean([np.std(per_layer[k]) / np.mean(per_layer[k]) for k in KNOBS]))
        pool.append(row)
    return pool


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="smollm2-135m")
    ap.add_argument("--ckpt", default=f"{RUNS}/sl135_lr2e-3/step2500")
    ap.add_argument("--texts", default=f"{HELDOUT}/heldout_ab.json")
    ap.add_argument("--n-pool", type=int, default=260)
    ap.add_argument("--per", type=int, default=4)
    ap.add_argument("--seed", type=int, default=8080)
    ap.add_argument("--ctx", type=int, default=1024)
    ap.add_argument("--out", default=f"{RUNS}/gt135_prosp/POOL.json")
    ap.add_argument("--no-score", action="store_true",
                    help="Emit the configs and their free statistics without running the slice.")
    a = ap.parse_args()

    from llmforge.supernet.config import SPECS
    spec = SPECS[a.model]
    pool = build_pool(spec, a.n_pool, a.per, a.seed)
    print(f"pool {len(pool)} at w={0.555}+-0.006, attn_share={0.22}+-0.012, seed={a.seed}")

    if not a.no_score:
        import torch, torch.nn.functional as F
        from transformers import AutoModelForCausalLM, AutoTokenizer
        from safetensors.torch import load_file
        from llmforge.supernet.elastic import (enable_elastic, pair_order_for, set_elastic_backend,
                                        set_elastic_config, add_elastic_temperature)
        tok = AutoTokenizer.from_pretrained(spec.repo)
        flat = []
        for t in json.load(open(a.texts)):
            flat += tok(t, add_special_tokens=False).input_ids
        ids = [torch.tensor(flat[i * a.ctx:(i + 1) * a.ctx], device="cuda").unsqueeze(0)
               for i in range(len(flat) // a.ctx)]
        print(f"{len(ids)} windows of {a.ctx}")
        m = AutoModelForCausalLM.from_pretrained(spec.repo, torch_dtype=torch.bfloat16,
                                                 attn_implementation="eager").to("cuda").eval()
        enable_elastic(m); set_elastic_backend("eager"); m.config.use_cache = False
        add_elastic_temperature(m)
        m.load_state_dict({k: v.to("cuda") for k, v in
                           load_file(f"{a.ckpt}/model.safetensors").items()}, strict=False)
        order = pair_order_for(spec)
        for i, r in enumerate(pool):
            p = r["per"]
            set_elastic_config(m, p["d_qk"], p["d_v"], order, n_h=p["n_h"], d_mlp=p["d_mlp"])
            s = n = 0
            with torch.no_grad():
                for x in ids:
                    lg = m(input_ids=x).logits[:, :-1].float()
                    s += F.cross_entropy(lg.reshape(-1, lg.shape[-1]), x[:, 1:].reshape(-1),
                                         reduction="sum").item()
                    n += x.shape[1] - 1
            r["slice"] = s / n
            if (i + 1) % 40 == 0:
                print(f"  scored {i+1}/{len(pool)}", flush=True)
        X = np.column_stack([np.ones(len(pool))] + [[r[f"mean_{k}"] for r in pool] for k in KNOBS])
        y = np.array([r["slice"] for r in pool])
        b, *_ = np.linalg.lstsq(X, y, rcond=None)
        for r, e in zip(pool, y - X @ b):
            r["slice_resid"] = float(e)
        res = np.array([r["slice_resid"] for r in pool])
        het = np.array([r["het"] for r in pool])
        print(f"\nslice residual sd {res.std(ddof=5):.4f}")
        print(f"POOL-LEVEL corr(slice_resid, het) = {np.corrcoef(res, het)[0,1]:+.3f}"
              f"   <- if this is large, the selected extremes are a het contrast, not a slice one")
        for k in KNOBS:
            v = np.array([r[f"sd_{k}"] for r in pool])
            print(f"  corr(slice_resid, sd_{k}) = {np.corrcoef(res, v)[0,1]:+.3f}")

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    json.dump(pool, open(a.out, "w"), indent=1)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
